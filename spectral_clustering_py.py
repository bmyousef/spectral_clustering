import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_circles
from sklearn.cluster import SpectralClustering
from sklearn.cluster import spectral_clustering
from sklearn.feature_extraction import image as sk_image
from skimage import data
from skimage.transform import rescale
from skimage.filters import gaussian

X, y = make_circles(
    n_samples=1000,
    factor=0.5,
    noise=0.05,
    random_state=42
)

# Step 2: Plot the dataset before clustering
plt.figure(figsize=(8, 6))
plt.scatter(X[:, 0], X[:, 1], color='gray')
plt.title("Dataset Before Spectral Clustering")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.savefig("spectral_data_before.png")
plt.show()

# Step 3: Apply Spectral Clustering
spectral = SpectralClustering(
    n_clusters=2,
    affinity="nearest_neighbors",
    random_state=42
)

labels = spectral.fit_predict(X)

# Step 4: Plot the dataset after clustering
plt.figure(figsize=(8, 6))
plt.scatter(X[:, 0], X[:, 1], c=labels, cmap='viridis')
plt.title("Dataset After Spectral Clustering")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.savefig("spectral_data_after.png")
plt.show()

from sklearn.feature_extraction.image import img_to_graph
image = data.coins()

# Step 2: Show the original image
plt.figure(figsize=(8, 6))
plt.imshow(image, cmap="gray")
plt.title("Coins Image Before Spectral Clustering")
plt.axis("off")
plt.savefig("spectral_image_before.png")
plt.show()

# Step 3: Smooth and resize the image
smooth_image = gaussian(image, sigma=2)
small_image = rescale(
    smooth_image,
    scale=0.2,
    anti_aliasing=True
)

# Convert the image into a graph
graph = img_to_graph(small_image)

# Adjust graph edge weights
graph.data = np.exp(
    -10 * graph.data / graph.data.std()
)

# Apply Spectral Clustering
labels = spectral_clustering(
    graph,
    n_clusters=25,
    assign_labels="discretize",
    random_state=42
)

# Reshape labels to match the small image
labels = labels.reshape(small_image.shape)

# Step 4: Display and save the result
plt.figure(figsize=(8, 6))
plt.imshow(labels, cmap="nipy_spectral")
plt.title("Coins Image After Spectral Clustering")
plt.axis("off")
plt.savefig("spectral_image_after.png")
plt.show()